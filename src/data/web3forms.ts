/**
 * Client-side email notification for new feedback.
 *
 * The app deliberately stays on Firebase's free Spark plan, so there is no
 * Cloud Function to email the admin. Web3Forms accepts a plain POST from static
 * hosting: the same browser that writes the Firestore document also sends the
 * mail. Its access key is designed to be public (it lives in hidden fields on
 * ordinary static sites); abuse is limited by Web3Forms, not by secrecy here.
 *
 * The notification is deliberately best-effort — Firestore is the source of
 * truth, and a mail failure must never turn a successful save into an error.
 */
const ENDPOINT = 'https://api.web3forms.com/submit';
const SUBJECT_PREFIX = '[TarneemAPP] ';
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

// expo-env.d.ts is gitignored and regenerated by an export, while CI runs
// typecheck before that. process.env.X is `any` there, so cast explicitly —
// the same pattern adminAccess.ts uses for its EXPO_PUBLIC_* reads.
const ACCESS_KEY: string =
  (process.env.EXPO_PUBLIC_WEB3FORMS_ACCESS_KEY as string | undefined)?.trim() ?? '';

export interface EmailFeedback {
  kind: 'rating' | 'message';
  rating: number;
  category: string;
  comment: string;
  replyEmail?: string;
  documentId?: string;
}

/** Sends the admin notification; never throws and never blocks the caller. */
export function notifyFeedbackByEmail(feedback: EmailFeedback): void {
  if (!ACCESS_KEY) return;

  const isMessage = feedback.kind === 'message';
  const replyEmail = (feedback.replyEmail ?? '').trim();
  const lines = [
    'New feedback for TarneemAPP',
    '',
    `kind: ${feedback.kind}`,
    `rating: ${feedback.rating}`,
    `category: ${feedback.category || '(none)'}`,
    `comment: ${feedback.comment || '(empty)'}`,
  ];
  if (replyEmail) lines.push(`replyEmail: ${replyEmail}`);
  if (feedback.documentId) lines.push(`documentId: ${feedback.documentId}`);

  const body = {
    access_key: ACCESS_KEY,
    subject: `${SUBJECT_PREFIX}${isMessage ? 'رسالة جديدة' : 'تقييم جديد'}`,
    message: lines.join('\n'),
    from_name: 'TarneemAPP',
    ...(isMessage && EMAIL_RE.test(replyEmail) ? { replyto: replyEmail } : {}),
  };

  try {
    void fetch(ENDPOINT, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
      body: JSON.stringify(body),
    })
      .then((response) => {
        if (!response.ok) {
          console.warn('[Web3Forms] rejected feedback notification', response.status);
        }
      })
      .catch((error: unknown) => {
        console.warn('[Web3Forms] feedback notification failed', error);
      });
  } catch (error) {
    console.warn('[Web3Forms] feedback notification failed', error);
  }
}
