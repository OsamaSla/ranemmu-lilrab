for (const h of hymns) {
  const { id, number, title, stanzas } = h;
  // build-book3.mjs expects: { hymns: [{ number, title, verses: [...] }] }
  const verses = stanzas.map(({ label, chorus, lines }) => ({
    label,
    ...(chorus ? { chorus: true } : {}),
    lines,
  }));
  const part = { hymns: [{ number, title, verses }] };
  const outPath = join(OUT, `${id}.json`);
  writeFileSync(outPath, JSON.stringify(part, null, 2), "utf8");
  console.log(`wrote ${outPath}`);
}
