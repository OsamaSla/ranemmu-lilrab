// 1. Fix 365-371 number field
for (let n = 365; n <= 371; n++) {
  const p = path.join(PARTS_DIR, `b300${n}.json`);
  if (fs.existsSync(p)) {
    const data = JSON.parse(fs.readFileSync(p, 'utf8'));
    data.hymns[0].number = n;
    fs.writeFileSync(p, JSON.stringify(data, null, 2), 'utf8');
    console.log(`Fixed number in ${p} -> ${n}`);
  }
}

