/**
 * Builds the bundled hymn corpus from the authoring files in content/.
 *
 * Run with: npm run build:corpus
 *
 * Inputs   content/*.json  — each file holds { hymns: Hymn[] }
 * Outputs  assets/hymns/index.json     light summaries for lists/grouping
 *          assets/hymns/full/NNN.json  chunks of full records, lazily loaded
 *          src/data/generated-chunks.ts  dynamic import() map (see below)
 *
 * Metro resolves `import()` arguments at build time, so every chunk is listed
 * as a literal `import('...json')` in the generated module. Because they are
 * dynamic rather than static requires, Metro emits one JS file per chunk and
 * the entry bundle only carries the summaries. The module also needs
 * regenerating whenever the corpus changes.
 */
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateCorpus, formatIssues } from './lib/validate.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT_DIR = join(ROOT, 'content');
const ASSET_DIR = join(ROOT, 'assets', 'hymns');
const FULL_DIR = join(ASSET_DIR, 'full');
const CHUNKS_FILE = join(ROOT, 'src', 'data', 'generated-chunks.ts');

/** Hymns per chunk. 100 keeps each file ~400 KB, so search loads ~5 MB total. */
const CHUNK_SIZE = 100;

/** Stable id from book + hymn number. The original corpus keeps its `hNNNN`
 *  ids so existing routes, favorites and recents keep working; other books
 *  use their own prefix (`trNNNN`, …). */
const ID_PREFIX = { main: 'h', taranim: 'tr' };
const idFor = (book, number) =>
  `${ID_PREFIX[book] ?? book.slice(0, 2)}${String(number).padStart(4, '0')}`;

async function readContent() {
  const entries = (await readdir(CONTENT_DIR))
    .filter((name) => name.endsWith('.json') && name !== 'authors.json')
    .sort();

  if (entries.length === 0) throw new Error(`no .json files in ${CONTENT_DIR}`);

  const hymns = [];
  for (const name of entries) {
    const raw = JSON.parse(await readFile(join(CONTENT_DIR, name), 'utf8'));
    const list = Array.isArray(raw) ? raw : raw.hymns;
    if (!Array.isArray(list)) throw new Error(`${name}: expected an array or { hymns: [] }`);
    hymns.push(...list);
  }
  return hymns;
}

function toSummary(hymn) {
  return {
    id: hymn.id ?? idFor(hymn.book ?? 'main', hymn.number),
    book: hymn.book ?? 'main',
    number: hymn.number,
    title: hymn.title,
    meter: hymn.meter,
    ...(hymn.mediaUrl ? { mediaUrl: hymn.mediaUrl } : {}),
    hasChorus: (hymn.verses ?? []).some((v) => v.chorus),
    ...(hymn.primaryTopic ? { primaryTopic: hymn.primaryTopic } : {}),
    ...(Array.isArray(hymn.topics) && hymn.topics.length > 0 ? { topics: hymn.topics } : {}),
  };
}

function generateChunksModule(chunks) {
  const loaders = chunks
    .map((chunk) => `  ${chunk.index}: () => import('../../assets/hymns/full/${chunk.file}'),`)
    .join('\n');

  const byId = chunks
    .flatMap((chunk) => chunk.ids.map((id) => `  '${id}': ${chunk.index},`))
    .join('\n');

  return `// AUTO-GENERATED by scripts/build-corpus.mjs — do not edit by hand.
// Run \`npm run build:corpus\` after changing anything in content/.

import type { Hymn } from './types';

const LOADERS: Record<number, () => Promise<unknown>> = {
${loaders}
};

/** Full hymn records, chunked. ${chunks.length} chunk(s) of up to ${CHUNK_SIZE}. */
export const HYMN_CHUNK_COUNT = ${chunks.length};

/** Which chunk holds each bundled hymn, so a reader loads only that one. */
export const HYMN_CHUNK_BY_ID: Record<string, number> = {
${byId}
};

/**
 * Imports one chunk on demand. The dynamic import keeps every chunk in its
 * own JS file, so the entry bundle carries only summaries until a hymn is
 * opened or a full-text search runs.
 */
export function loadHymnChunk(index: number): Promise<Hymn[]> {
  const load = LOADERS[index];
  if (!load) return Promise.reject(new Error(\`unknown hymn chunk \${index}\`));
  // Metro may hand back the array directly or under \`default\`; the JSON's
  // own type inference is looser than Hymn (book is a plain string), so the
  // corpus contract is asserted here once.
  return load().then(
    (mod) => ((mod as { default?: Hymn[] }).default ?? mod) as Hymn[],
  );
}
`;
}

async function main() {
  const raw = await readContent();

  const issues = validateCorpus(raw);
  if (issues.length > 0) {
    console.error(`corpus validation failed (${issues.length} issue(s)):\n${formatIssues(issues)}`);
    process.exit(1);
  }

  // Normalise: assign ids, default the book, sort by book then hymn
  // number, and default the chorus flags.
  const hymns = raw
    .map((hymn) => ({
      ...hymn,
      book: hymn.book ?? 'main',
      id: hymn.id ?? idFor(hymn.book ?? 'main', hymn.number),
      verses: (hymn.verses ?? []).map((verse) => ({
        ...verse,
        chorus: verse.chorus ?? false,
      })),
    }))
    .sort((a, b) => (a.book < b.book ? -1 : a.book > b.book ? 1 : a.number - b.number));

  const duplicates = hymns
    .map((h) => h.id)
    .filter((id, i, all) => all.indexOf(id) !== i);
  if (duplicates.length > 0) {
    console.error(`duplicate ids: ${[...new Set(duplicates)].join(', ')}`);
    process.exit(1);
  }

  await rm(ASSET_DIR, { recursive: true, force: true });
  await mkdir(FULL_DIR, { recursive: true });

  const summaries = hymns.map(toSummary);
  await writeFile(join(ASSET_DIR, 'index.json'), JSON.stringify(summaries, null, 1) + '\n');

  const chunks = [];
  for (let i = 0; i < hymns.length; i += CHUNK_SIZE) {
    const index = chunks.length;
    const file = `${String(index).padStart(3, '0')}.json`;
    const slice = hymns.slice(i, i + CHUNK_SIZE);
    await writeFile(join(FULL_DIR, file), JSON.stringify(slice) + '\n');
    chunks.push({ index, file, ids: slice.map((hymn) => hymn.id) });
  }

  await writeFile(CHUNKS_FILE, generateChunksModule(chunks));

  const bytes = summaries.length === 0 ? 0 : JSON.stringify(hymns).length;
  console.log(
    `${hymns.length} hymns -> ${chunks.length} chunk(s), ` +
      `index ${(JSON.stringify(summaries).length / 1024).toFixed(0)} KB, ` +
      `full ~${(bytes / 1024 / 1024).toFixed(2)} MB`,
  );
  console.log('wrote assets/hymns/ and src/data/generated-chunks.ts');
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
